import Link from "next/link";
import { and, desc, eq, gte, sql } from "drizzle-orm";
import { ArrowLeft, BadgeIndianRupee, CalendarDays, ShieldCheck, TrendingUp, Users } from "lucide-react";
import { withTenant } from "@/db/client";
import { businessImpacts, investors, users } from "@/db/schema";
import { requireSession } from "@/lib/auth/session";
import { require as requireCap } from "@/lib/auth/rbac";
import { formatDate, formatINR } from "@/lib/utils";
import { TableScroll } from "@/components/common/TableScroll";

export const dynamic = "force-dynamic";

const PERIODS = [
  ["30", "30 days"],
  ["90", "90 days"],
  ["365", "1 year"],
  ["all", "All time"],
] as const;

const SOURCE_LABELS: Record<string, string> = {
  workflow: "Workflow",
  campaign: "Campaign",
  next_best_action: "Next best action",
  service: "Service request",
  meeting: "Meeting",
  manual: "Manual follow-up",
};

const OUTCOME_LABELS: Record<string, string> = {
  aum_protected: "AUM protected",
  aum_generated: "AUM generated",
  sip_recovered: "SIP recovered",
  sip_started: "New SIP",
  referral_won: "Referral won",
  service_recovery: "Service recovery",
};

export default async function ImpactAttributionPage({ searchParams }: { searchParams: Promise<{ period?: string }> }) {
  const session = await requireSession();
  requireCap(session.roles, "investor.view.all", session.permissions);
  const sp = await searchParams;
  const period = PERIODS.some(([value]) => value === sp.period) ? (sp.period ?? "90") : "90";
  const since = period === "all" ? null : new Date(Date.now() - Number(period) * 86_400_000);

  const data = await withTenant(session.tenantId, async (tx) => {
    const condition = since ? gte(businessImpacts.occurredAt, since) : undefined;
    const totals = await tx.select({
      events: sql<number>`count(*)::int`,
      amount: sql<string>`coalesce(sum(${businessImpacts.amount}), 0)`,
      monthlySip: sql<string>`coalesce(sum(${businessImpacts.monthlySipAmount}), 0)`,
      clients: sql<number>`count(distinct ${businessImpacts.investorId})::int`,
    }).from(businessImpacts).where(condition);
    const bySource = await tx.select({
      source: businessImpacts.sourceType,
      events: sql<number>`count(*)::int`,
      amount: sql<string>`coalesce(sum(${businessImpacts.amount}), 0)`,
      monthlySip: sql<string>`coalesce(sum(${businessImpacts.monthlySipAmount}), 0)`,
    }).from(businessImpacts).where(condition).groupBy(businessImpacts.sourceType).orderBy(desc(sql`sum(${businessImpacts.amount})`));
    const byOutcome = await tx.select({
      outcome: businessImpacts.outcome,
      events: sql<number>`count(*)::int`,
      amount: sql<string>`coalesce(sum(${businessImpacts.amount}), 0)`,
      monthlySip: sql<string>`coalesce(sum(${businessImpacts.monthlySipAmount}), 0)`,
    }).from(businessImpacts).where(condition).groupBy(businessImpacts.outcome).orderBy(desc(sql`sum(${businessImpacts.amount})`));
    const recent = await tx.select({
      id: businessImpacts.id,
      source: businessImpacts.sourceType,
      outcome: businessImpacts.outcome,
      amount: businessImpacts.amount,
      monthlySip: businessImpacts.monthlySipAmount,
      note: businessImpacts.note,
      occurredAt: businessImpacts.occurredAt,
      investorId: businessImpacts.investorId,
      investorName: investors.name,
      recordedBy: users.name,
    }).from(businessImpacts)
      .leftJoin(investors, and(eq(investors.id, businessImpacts.investorId), eq(investors.tenantId, businessImpacts.tenantId)))
      .leftJoin(users, eq(users.id, businessImpacts.recordedByUserId))
      .where(condition).orderBy(desc(businessImpacts.occurredAt)).limit(100);
    return { totals: totals[0], bySource, byOutcome, recent };
  });

  const total = data.totals ?? { events: 0, amount: "0", monthlySip: "0", clients: 0 };

  return (
    <div className="max-w-7xl space-y-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div><Link href="/dashboard/reports" className="mb-2 inline-flex items-center gap-1 text-xs text-muted-foreground hover:text-foreground"><ArrowLeft className="size-3.5" /> Reports</Link><h1 className="page-title"><BadgeIndianRupee className="size-6 text-brand-cyan" /> Impact attribution</h1><p className="mt-1 text-sm text-muted-foreground">Business protected or generated by workflows, campaigns, meetings and team actions.</p></div>
        <div className="inline-flex rounded-lg border bg-secondary/40 p-0.5 text-xs">{PERIODS.map(([value, label]) => <Link key={value} href={`/dashboard/reports/impact-attribution?period=${value}`} className={`rounded-md px-2.5 py-1.5 font-medium ${period === value ? "bg-card shadow-sm" : "text-muted-foreground"}`}>{label}</Link>)}</div>
      </div>

      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        <Kpi icon={ShieldCheck} label="AUM impact" value={formatINR(Number(total.amount))} />
        <Kpi icon={TrendingUp} label="Monthly SIP impact" value={`${formatINR(Number(total.monthlySip))}/mo`} />
        <Kpi icon={Users} label="Clients affected" value={String(total.clients)} />
        <Kpi icon={CalendarDays} label="Recorded outcomes" value={String(total.events)} />
      </div>

      <div className="grid gap-4 lg:grid-cols-2">
        <Breakdown title="By source" rows={data.bySource.map((row) => ({ label: SOURCE_LABELS[row.source] ?? row.source, ...row }))} />
        <Breakdown title="By outcome" rows={data.byOutcome.map((row) => ({ label: OUTCOME_LABELS[row.outcome] ?? row.outcome, ...row }))} />
      </div>

      <section><h2 className="mb-3 font-semibold">Evidence ledger</h2><TableScroll className="rounded-lg border bg-card"><table className="w-full text-sm"><thead><tr><th className="text-left">Date</th><th className="text-left">Client</th><th className="text-left">Outcome</th><th className="text-left">Source</th><th className="text-right">AUM</th><th className="text-right">Monthly SIP</th><th className="text-left">Recorded by</th></tr></thead><tbody>{data.recent.length ? data.recent.map((row) => <tr key={row.id}><td>{formatDate(row.occurredAt)}</td><td>{row.investorId ? <Link href={`/dashboard/investors/${row.investorId}`} className="font-medium hover:underline">{row.investorName ?? "Client"}</Link> : "—"}</td><td>{OUTCOME_LABELS[row.outcome] ?? row.outcome}</td><td>{SOURCE_LABELS[row.source] ?? row.source}</td><td className="text-right tabular-nums">{Number(row.amount) ? formatINR(Number(row.amount)) : "—"}</td><td className="text-right tabular-nums">{Number(row.monthlySip) ? formatINR(Number(row.monthlySip)) : "—"}</td><td className="text-muted-foreground">{row.recordedBy ?? "System"}</td></tr>) : <tr><td colSpan={7} className="py-10 text-center text-muted-foreground">No outcomes recorded in this period. Use “Record outcome” on a client profile.</td></tr>}</tbody></table></TableScroll></section>
    </div>
  );
}

function Kpi({ icon: Icon, label, value }: { icon: typeof ShieldCheck; label: string; value: string }) {
  return <div className="rounded-lg border bg-card p-4"><Icon className="size-4 text-primary" /><div className="mt-3 text-xs text-muted-foreground">{label}</div><div className="mt-0.5 text-xl font-bold tabular-nums">{value}</div></div>;
}

function Breakdown({ title, rows }: { title: string; rows: Array<{ label: string; events: number; amount: string; monthlySip: string }> }) {
  const max = Math.max(1, ...rows.map((row) => Number(row.amount) + Number(row.monthlySip) * 12));
  return <section className="rounded-lg border bg-card p-4"><h2 className="font-semibold">{title}</h2><div className="mt-4 space-y-4">{rows.length ? rows.map((row) => { const value = Number(row.amount) + Number(row.monthlySip) * 12; return <div key={row.label}><div className="flex justify-between gap-3 text-sm"><span className="font-medium">{row.label}</span><span className="text-muted-foreground">{row.events} outcomes · {formatINR(Number(row.amount))}{Number(row.monthlySip) ? ` + ${formatINR(Number(row.monthlySip))}/mo` : ""}</span></div><div className="mt-1.5 h-1.5 overflow-hidden rounded-full bg-secondary"><div className="h-full bg-primary" style={{ width: `${Math.max(3, (value / max) * 100)}%` }} /></div></div>; }) : <p className="py-8 text-center text-sm text-muted-foreground">No impact data yet.</p>}</div></section>;
}
